# проверки
for p in P:
    base = ev(p['t'])
    last = p['t']
    for s in p['steps']:
        assert 0 <= s['ok'] < len(s['opts']), (p['t'], s['q'])
        if 'e' in s:
            assert ev(s['e']) == base, (p['t'], s['e'])
            last = s['e']
    p['fin'] = p.get('fin', last)
    if p['fin'] != 'не се разлага':
        assert ev(p['fin']) == base
