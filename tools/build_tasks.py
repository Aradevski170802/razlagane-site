YN = ['да', 'не']


def Q1(ans, hint, note=''):
    return dict(node='Q1', q='Има ли множител, който е във <b>всеки</b> член?', opts=YN, ok=0 if ans else 1, hint=hint, note=note)


def A1(opts, ok, e, hint, note=''):
    return dict(node='A1', q='Кой е общият множител?', opts=opts, ok=ok, e=e, hint=hint, note=note)


def Q2(what, n, hint):
    return dict(node='Q2', q='Колко члена има %s?' % what, opts=['2', '3', '4'], ok=[2, 3, 4].index(n), hint=hint)


def B2type(ok, hint, note=''):
    return dict(node='B2', q='Какво виждаш?', opts=['разлика на квадрати', 'сбор на квадрати', 'разлика на кубове', 'сбор на кубове'],
                ok=ok, hint=hint, note=note)


def Q5(ans, what, hint, note=''):
    return dict(node='Q5', q='Разлага ли се още нещо? Погледни %s.' % what, opts=YN, ok=0 if ans else 1, hint=hint, note=note)


